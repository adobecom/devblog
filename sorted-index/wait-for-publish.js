// Polls /en/query-index.json until the article path from the triggering
// AEM repository_dispatch event actually appears in it, or until a bounded
// number of attempts is exhausted.
//
// This exists because AEM's repository_dispatch fires at publish time, but
// query-index.json is regenerated by a separate, asynchronous indexing
// step — so the index may not yet contain the article when this workflow
// run starts. Without waiting, sort-query-index.js could run its diff
// against a query-index.json snapshot that doesn't include the very
// article that triggered the run.
//
// Never fails the workflow on timeout: if the article still isn't in the
// index after MAX_ATTEMPTS, this script logs a warning and exits 0 so
// indexing proceeds as normal. The permanent known-articles.json record
// (maintained by sort-query-index.js) ensures the article will still be
// correctly detected as new whenever a later run's fetch does include it —
// this step is a best-effort optimization to catch it in the *same* run
// that triggered it, not a correctness requirement.

const https = require('https');

const QUERY_INDEX_URL = 'https://blog.developer.adobe.com/en/query-index.json';
const ARTICLE_PATH = process.env.ARTICLE_PATH;
const MAX_ATTEMPTS = parseInt(process.env.WAIT_MAX_ATTEMPTS || '10', 10);
const POLL_INTERVAL_MS = parseInt(process.env.WAIT_POLL_INTERVAL_MS || '15000', 10);

function fetchData(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      let data = '';
      res.on('data', (chunk) => { data += chunk; });
      res.on('end', () => {
        if (res.statusCode >= 200 && res.statusCode < 300) {
          resolve(data);
        } else {
          reject(new Error(`HTTP ${res.statusCode}: ${res.statusMessage}`));
        }
      });
    }).on('error', reject);
  });
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function main() {
  if (!ARTICLE_PATH) {
    // Not a repository_dispatch run with a known path (e.g. manual
    // workflow_dispatch) — nothing specific to wait for.
    console.log('No ARTICLE_PATH provided, skipping wait.');
    return;
  }

  console.log(`Waiting for "${ARTICLE_PATH}" to appear in query-index.json (up to ${MAX_ATTEMPTS} attempts, ${POLL_INTERVAL_MS}ms apart)`);

  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    try {
      const response = await fetchData(QUERY_INDEX_URL);
      const parsed = JSON.parse(response);
      const found = Array.isArray(parsed.data) && parsed.data.some((a) => a.path === ARTICLE_PATH);

      if (found) {
        console.log(`✅ Found "${ARTICLE_PATH}" in query-index.json after ${attempt} attempt(s).`);
        return;
      }

      console.log(`⏳ Attempt ${attempt}/${MAX_ATTEMPTS}: "${ARTICLE_PATH}" not yet in query-index.json.`);
    } catch (err) {
      console.warn(`Attempt ${attempt}/${MAX_ATTEMPTS}: error fetching query-index.json:`, err.message);
    }

    if (attempt < MAX_ATTEMPTS) {
      await sleep(POLL_INTERVAL_MS);
    }
  }

  console.warn(`⚠️ Timed out waiting for "${ARTICLE_PATH}" to appear after ${MAX_ATTEMPTS} attempts. Proceeding anyway — the permanent known-articles record ensures it will still be detected correctly on a later run.`);
}

main();